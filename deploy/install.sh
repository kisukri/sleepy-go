#!/usr/bin/env bash
# install / update / migrate from py sleepy. env knobs -> README
set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/kisukri/sleepy-go.git}"
BRANCH="${BRANCH:-main}"
OLD_DIR="${OLD_DIR:-$HOME/sleepy}"
REMOVE_OLD="${REMOVE_OLD:-1}"
LISTEN="${LISTEN:-}" # 127.0.0.1 = behind your own proxy, "-" = back to public
ALLOWED_HOSTS="${ALLOWED_HOSTS:-}"
PAGE_LANGUAGE="${PAGE_LANGUAGE:-}" # ja / zh / en
SERVICE=sleepy-go
COMPOSE_FILE=docker-compose.yml

say() { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[!]\033[0m %s\n' "$*" >&2; }
die() { printf '\033[1;31m[x]\033[0m %s\n' "$*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || die "missing command: $1"; }

# run from a checkout -> install there
if [ -z "${INSTALL_DIR:-}" ] && [ -n "${BASH_SOURCE[0]:-}" ] && [ -f "${BASH_SOURCE[0]}" ]; then
	self=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
	if [ -f "$self/go.mod" ] && grep -q '^module github.com/kisukri/sleepy-go' "$self/go.mod"; then
		INSTALL_DIR=$self
	fi
fi
INSTALL_DIR="${INSTALL_DIR:-$HOME/sleepy-go}"

case "$PAGE_LANGUAGE" in "" | ja | zh | en) ;; *) die "PAGE_LANGUAGE must be ja, zh or en" ;; esac
need git
need docker
need curl
docker compose version >/dev/null 2>&1 || die "Docker Compose plugin is required (docker compose)"

health() {
	local i
	for i in $(seq 1 30); do
		curl -fs -o /dev/null "http://127.0.0.1:${PORT}/none" && return 0
		sleep 1
	done
	return 1
}

is_python_sleepy() {
	[ -f "$1/main.py" ] && [ -d "$1/data" ] && [ "$(cd "$1" && pwd)" != "$(cd "$INSTALL_DIR" 2>/dev/null && pwd)" ]
}

# KEY\tVALUE for every sleepy_* env line, list or map form, quoted or not
compose_settings() {
	[ -f "$1" ] || return 0
	sed -E -e 's/^[[:space:]]*-[[:space:]]*"(.*)"[[:space:]]*$/- \1/' \
		-e "s/^[[:space:]]*-[[:space:]]*'(.*)'[[:space:]]*\$/- \\1/" "$1" |
		sed -nE 's/^[[:space:]]*-?[[:space:]]*([Ss][Ll][Ee][Ee][Pp][Yy]_[A-Za-z0-9_]+)[[:space:]]*[:=][[:space:]]*(.*)$/\1\t\2/p' |
		while IFS=$'\t' read -r key value; do
			value=$(printf '%s' "$value" | sed -E 's/[[:space:]]+#.*$//; s/^[[:space:]]+//; s/[[:space:]]+$//')
			case "$value" in
			\"*\") value=${value#\"}; value=${value%\"} ;;
			\'*\') value=${value#\'}; value=${value%\'} ;;
			esac
			value=${value//\'\'/\'}
			printf '%s\t%s\n' "$(printf '%s' "$key" | tr 'A-Z' 'a-z')" "$value"
		done
}

compose_port() { sed -nE 's/^[[:space:]]*-[[:space:]]*"?([0-9.]+:)?([0-9]+):9010"?.*/\2/p' "$1" 2>/dev/null | head -n1; }
compose_listen() { sed -nE 's/^[[:space:]]*-[[:space:]]*"?([0-9.]+):[0-9]+:9010"?.*/\1/p' "$1" 2>/dev/null | head -n1; }

yaml_quote() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/''/g")"; }

write_compose() { # owner, then KEY=VALUE...
	local owner=$1 kv
	shift
	(
		umask 077
		{
			echo "# generated by deploy/install.sh - has the secret, not in git"
			echo "services:"
			echo "  ${SERVICE}:"
			echo "    build:"
			echo "      context: ."
			echo "      dockerfile: deploy/docker/Dockerfile"
			echo "    image: sleepy-go:local"
			echo "    user: \"${owner}\""
			echo "    ports:"
			echo "      - \"${LISTEN:+${LISTEN}:}${PORT}:9010\""
			echo "    volumes:"
			echo "      - ./data:/sleepy/data"
			echo "    restart: unless-stopped"
			if [ "$#" -gt 0 ]; then
				echo "    environment:"
				for kv in "$@"; do
					echo "      - $(yaml_quote "$kv")"
				done
			fi
		} >"$INSTALL_DIR/$COMPOSE_FILE"
	)
}

# ALLOWED_HOSTS / PAGE_LANGUAGE given -> replaces whatever was there ("-" clears hosts)
with_hosts() {
	local kv
	for kv in "$@"; do
		case "$kv" in
		sleepy_main_allowed_hosts=*) [ -n "$ALLOWED_HOSTS" ] || printf '%s\n' "$kv" ;;
		sleepy_page_language=*) [ -n "$PAGE_LANGUAGE" ] || printf '%s\n' "$kv" ;;
		*) printf '%s\n' "$kv" ;;
		esac
	done
	[ -n "$ALLOWED_HOSTS" ] && [ "$ALLOWED_HOSTS" != "-" ] && printf 'sleepy_main_allowed_hosts=%s\n' "$ALLOWED_HOSTS"
	[ -n "$PAGE_LANGUAGE" ] && printf 'sleepy_page_language=%s\n' "$PAGE_LANGUAGE"
	return 0
}

compose() { (cd "$INSTALL_DIR" && docker compose "$@"); }

finish_msg() {
	echo
	if [ "${LISTEN:-}" = "127.0.0.1" ]; then
		echo "Sleepy Go: http://127.0.0.1:${PORT}/ (local only - point your reverse proxy here, see deploy/examples/)"
	else
		echo "Sleepy Go: http://<server-ip>:${PORT}/   admin: http://<server-ip>:${PORT}/panel"
	fi
	echo "Directory: ${INSTALL_DIR}"
	echo "Update:    bash ${INSTALL_DIR}/deploy/install.sh"
}

# --- code
if [ -d "$INSTALL_DIR/.git" ]; then
	say "Updating $INSTALL_DIR"
	git -C "$INSTALL_DIR" pull --ff-only || die "git pull failed (local changes?). Nothing was changed."
elif [ -e "$INSTALL_DIR" ] && [ -n "$(ls -A "$INSTALL_DIR" 2>/dev/null)" ]; then
	die "$INSTALL_DIR exists and is not a git checkout; set INSTALL_DIR to another path"
else
	say "Cloning $REPO_URL ($BRANCH) into $INSTALL_DIR"
	git clone --branch "$BRANCH" "$REPO_URL" "$INSTALL_DIR"
fi

# --- update
if [ -f "$INSTALL_DIR/$COMPOSE_FILE" ]; then
	PORT="${PORT:-$(compose_port "$INSTALL_DIR/$COMPOSE_FILE")}"
	PORT="${PORT:-9010}"
	current_listen=$(compose_listen "$INSTALL_DIR/$COMPOSE_FILE")
	if [ -n "$ALLOWED_HOSTS" ] || [ -n "$PAGE_LANGUAGE" ] || { [ -n "$LISTEN" ] && [ "$LISTEN" != "$current_listen" ]; }; then
		say "Rewriting ${COMPOSE_FILE} (settings kept)"
		if [ "$LISTEN" = "-" ]; then LISTEN=""; elif [ -z "$LISTEN" ]; then LISTEN="$current_listen"; fi
		kept=()
		while IFS=$'\t' read -r key value; do kept+=("$key=$value"); done < <(compose_settings "$INSTALL_DIR/$COMPOSE_FILE")
		mapfile -t kept < <(with_hosts ${kept[@]+"${kept[@]}"})
		write_compose "$(stat -c '%u:%g' "$INSTALL_DIR/data")" ${kept[@]+"${kept[@]}"}
	else
		LISTEN="$current_listen"
	fi
	say "Building image"
	compose build
	say "Restarting (a few seconds of downtime)"
	compose up -d --force-recreate --remove-orphans
	health || { compose logs --tail=50; die "service did not answer on port ${PORT}"; }
	say "Updated: $(git -C "$INSTALL_DIR" log --oneline -1)"
	finish_msg
	exit 0
fi

# --- first install
MIGRATE=0
if is_python_sleepy "$OLD_DIR"; then
	MIGRATE=1
	say "Found the original Sleepy in $OLD_DIR; migrating its data"
	for f in "$OLD_DIR"/data/config.yaml "$OLD_DIR"/data/config.toml "$OLD_DIR"/data/config.json; do
		[ -f "$f" ] || continue
		if grep -Eqi 'theme[^a-z_]*[:=][^a-z]*(default|dark|blue|console|github|simple)|theme_detect' "$f"; then
			die "$f uses a Python-only theme or plugin. Set page.theme to paper and keep plugins_enabled to custom_text, v4_compatible, auto_dead, then run again. Nothing was changed."
		fi
	done
fi
settings=()
secret_set=0
name_set=0
if [ "$MIGRATE" = 1 ]; then
	old_port=$(compose_port "$OLD_DIR/docker-compose.yml" || true)
	PORT="${PORT:-${old_port:-9010}}"
	while IFS=$'\t' read -r key value; do
		case "$key" in
		sleepy_main_host | sleepy_main_port | sleepy_main_colorful_log | sleepy_main_debug | sleepy_main_log_file) continue ;;
		sleepy_main_secret) [ -n "${SECRET:-}" ] && continue; [ -n "$value" ] && secret_set=1 ;;
		sleepy_page_name) [ -n "${PAGE_NAME:-}" ] && continue; name_set=1 ;;
		sleepy_page_language) [ -z "$PAGE_LANGUAGE" ] && PAGE_LANGUAGE=$value; continue ;;
		esac
		settings+=("$key=$value")
	done < <(compose_settings "$OLD_DIR/docker-compose.yml")
	# old sleepy was zh-only; keep its status names
	PAGE_LANGUAGE="${PAGE_LANGUAGE:-zh}"
	# secret in old data/ travels w/ data
	if grep -Eqis '^[[:space:]]*(secret[[:space:]]*:|sleepy_main_secret[[:space:]]*=)' "$OLD_DIR"/data/config.* "$OLD_DIR"/data/.env 2>/dev/null; then
		secret_set=1
	fi
else
	PORT="${PORT:-9010}"
fi
GENERATED_SECRET=""
if [ -n "${SECRET:-}" ]; then
	settings+=("sleepy_main_secret=$SECRET")
elif [ "$secret_set" = 0 ]; then
	GENERATED_SECRET=$(head -c 32 /dev/urandom | base64 | tr -d '/+=\n' | cut -c1-32)
	settings+=("sleepy_main_secret=$GENERATED_SECRET")
fi
if [ -n "${PAGE_NAME:-}" ]; then
	settings+=("sleepy_page_name=$PAGE_NAME")
elif [ "$name_set" = 0 ]; then
	settings+=("sleepy_page_name=Sleepy")
fi
mapfile -t settings < <(with_hosts ${settings[@]+"${settings[@]}"})

[ "$LISTEN" = "-" ] && LISTEN=""
mkdir -p "$INSTALL_DIR/data"
if [ "$MIGRATE" = 1 ]; then
	owner=$(stat -c '%u:%g' "$OLD_DIR/data")
else
	owner=$(stat -c '%u:%g' "$INSTALL_DIR/data")
fi
write_compose "$owner" ${settings[@]+"${settings[@]}"}

if [ "$MIGRATE" = 1 ]; then
	say "Building image (the old version keeps running meanwhile)"
else
	say "Building image"
fi
compose build

BACKUP=""
if [ "$MIGRATE" = 1 ]; then
	say "Stopping the old version"
	if [ -f "$OLD_DIR/docker-compose.yml" ]; then
		(cd "$OLD_DIR" && docker compose down) || warn "could not stop the old compose project; continuing"
	fi
	BACKUP="$HOME/sleepy-python-backup-$(date +%Y%m%d-%H%M%S).tgz"
	say "Backing up $OLD_DIR to $BACKUP"
	tar czf "$BACKUP" -C "$(dirname "$OLD_DIR")" "$(basename "$OLD_DIR")"
	rm -rf "$INSTALL_DIR/data"
	cp -a "$OLD_DIR/data" "$INSTALL_DIR/data"
fi

say "Starting Sleepy Go on port ${PORT}"
compose up -d --remove-orphans
if ! health; then
	compose logs --tail=50 || true
	if [ "$MIGRATE" = 1 ] && [ -f "$OLD_DIR/docker-compose.yml" ]; then
		warn "Sleepy Go did not start; restoring the old version"
		compose down || true
		# rename -> next run migrates again instead of "updating"
		mv -f "$INSTALL_DIR/$COMPOSE_FILE" "$INSTALL_DIR/$COMPOSE_FILE.failed"
		(cd "$OLD_DIR" && docker compose up -d) || true
		die "Rolled back to $OLD_DIR (see $INSTALL_DIR/$COMPOSE_FILE.failed). Backup: $BACKUP"
	fi
	die "service did not answer on port ${PORT}"
fi

if [ "$MIGRATE" = 1 ] && [ "$REMOVE_OLD" = 1 ]; then
	say "Removing the old version (backup: $BACKUP)"
	if [ -f "$OLD_DIR/docker-compose.yml" ]; then
		(cd "$OLD_DIR" && docker compose down --rmi local --remove-orphans >/dev/null 2>&1) || true
	fi
	rm -rf "$OLD_DIR"
fi

finish_msg
if [ -n "$GENERATED_SECRET" ]; then
	echo "Generated secret (admin login and device clients): ${GENERATED_SECRET}"
	echo "Stored in ${INSTALL_DIR}/${COMPOSE_FILE}."
fi
[ -n "$BACKUP" ] && echo "Old version backup: ${BACKUP}"
exit 0
